/** Run `fn` with console.{log,error,warn} and process.stdout.write captured. */
async function capture(fn, { stdout = false } = {}) {
    const out = [], err = [];
    const orig = { log: console.log, error: console.error, warn: console.warn };
    const origWrite = process.stdout.write;
    console.log = (...a) => out.push(a.map(String).join(' '));
    console.error = (...a) => err.push(a.map(String).join(' '));
    console.warn = (...a) => err.push(a.map(String).join(' '));
    if (stdout) process.stdout.write = (chunk) => { out.push(String(chunk)); return true; };
    try {
        const value = await fn();
        return { value, out, err, threw: null };
    } catch (e) {
        return { value: undefined, out, err, threw: e };
    } finally {
        console.log = orig.log; console.error = orig.error; console.warn = orig.warn;
        if (stdout) process.stdout.write = origWrite;
    }
}

/** Replace process.exit with a thrower so a CLI's exit path is observable. */
class ExitSignal extends Error {
    constructor(code) { super(`process.exit(${code})`); this.code = code; }
}
async function withExitTrap(fn) {
    const real = process.exit;
    process.exit = (code) => { throw new ExitSignal(code); };
    try { return await fn(); } finally { process.exit = real; }
}

