test('migrate-dsl: FIXED — the migration is idempotent for the `flag` sugar verbs', () => {
    // WAS (until 2026-07-31): `detonate` -> `flag detonate`, but the table still
    // matched the bare word inside its own output, so a second pass produced
    // `flag flag detonate`. api/data/rules/weapon-qualities.dsl:22, :506 and
    // :546 already ship those expanded forms, so
    // `node tools/migrate-dsl.mjs --all --write` corrupted the repository's own
    // rule files on the FIRST run — verified: 3 corruptions introduced.
    // NOW an expansion is skipped when `flag ` already precedes the verb.
    for (const verb of ['detonate', 'keep_highest', 'cannot_parry']) {
        const already = `dsl 3\nquality "r" { then flag ${verb} }`;
        const once = migrateDsl(already);
        assert.equal(once.text, already, `flag ${verb} must be a fixed point`);
        assert.equal(once.changes, 0, `flag ${verb} needs no migration`);
        // and the bare verb still expands exactly once
        const bare = migrateDsl(`dsl 3\nquality "r" { then ${verb} }`);
        assert.equal(bare.text, `dsl 3\nquality "r" { then flag ${verb} }`);
        assert.equal(bare.changes, 1);
        // re-running the expanded output is a no-op
        assert.equal(migrateDsl(bare.text).text, bare.text);
    }
    // the verbs that expand to `set …` are stable
    const stable = migrateDsl('dsl 3\nquality "r" { then set extra_dice += 1 }');
    assert.equal(stable.changes, 0);
});

