test('serve-static: unknown paths 404 and traversal attempts cannot escape docs/', async () => {
    await runServeStatic();
    const missing = await request('/no-such-file.html');
    assert.equal(missing.status, 404);
    assert.equal(missing.type, 'text/plain');
    assert.equal(missing.body, '404 Not Found');
    // the WHATWG URL parser resolves dot segments (encoded or not) before the
    // handler sees them, so these all land inside docs/ and 404.
    for (const url of ['/../../package.json', '/%2e%2e/%2e%2e/package.json',
        '/a/%2e%2e/%2e%2e/%2e%2e/package.json', '/..%2f..%2fpackage.json']) {
        const res = await request(url);
        assert.equal(res.status, 404, `${url} must not escape docs/`);
    }
    const decoded = await request('/style%2ecss');
    assert.equal(decoded.status, 200, 'percent-decoding of ordinary names still works');
});

