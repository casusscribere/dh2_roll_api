// ── real-artifact fingerprints (asserted unchanged at the end) ──────────────
const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');
const treeFingerprint = (dir) => {
    if (!existsSync(dir)) return 'ABSENT';
    const walk = (d) => readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))
        .map((e) => (e.isDirectory() ? `${e.name}/[${walk(join(d, e.name))}]` : `${e.name}:${sha(join(d, e.name))}`))
        .join(',');
    return walk(dir);
};
