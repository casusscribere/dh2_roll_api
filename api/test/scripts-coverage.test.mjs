test('main.mjs: readEncounterFromActor reads managed AEs back into an EncounterState', async () => {
    const vm = await readyVm();
    const enc = vm.readEncounterFromActor({
        name: 'Warden',
        effects: [
            { name: 'On Fire', duration: { rounds: 2 }, flags: { 'dh2-roll-vm': { managed: true, severity: 3, location: 'body', decay: 1 } } },
            { name: 'Blessed', duration: {}, flags: { 'dh2-roll-vm': { managed: false } } },
            { name: 'Foreign', duration: {}, flags: {} },
        ],
    });
    const entry = Object.values(enc.actors)[0];
    assert.equal(entry.name, 'Warden');
    assert.equal(entry.conditions.length, 1, 'unmanaged AEs are ignored');
    assert.deepEqual(entry.conditions[0],
        { name: 'On Fire', severity: 3, duration: 2, location: 'body', decay: 1 });

    const noDecay = vm.readEncounterFromActor({
        name: 'Other',
        effects: [{ name: 'Stunned', duration: {}, flags: { 'dh2-roll-vm': { managed: true } } }],
    }, 'custom-key');
    assert.ok('custom-key' in noDecay.actors, 'the key argument is honoured');
    const c = Object.values(noDecay.actors)[0].conditions[0];
    assert.deepEqual(c, { name: 'Stunned', severity: null, duration: null, location: null });
    assert.ok(!('decay' in c), 'decay is omitted when absent');
});

