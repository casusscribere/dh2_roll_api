/**
 * Standalone engine library bundle for embedding hosts (the rogue-trader-2e
 * Foundry system vendors this — architecture: "the engine bundle is imported
 * by the system; zero foundry./game. globals inside it; stateless").
 *
 * Same recipe as scripts/build-foundry.mjs (inline the rule/weapon data via a
 * generated sources twin, esbuild ESM), but the entry is a pure library
 * surface instead of the dh2-roll-vm module UI:
 *
 *   import { dispatch, CHARACTER_SCHEMA_VERSION, migrateCharacter,
 *            validateCharacter, emptyCharacter, characterToCombatant,
 *            characteristicTotal, ENGINE_LIB_VERSION } from 'dh2-engine.mjs'
 *
 * Everything else (rules, chargen pack, advancement, engage phases) is
 * reachable THROUGH dispatch — the single seam.
 *
 * Run: npm run build:engine-lib     Output: dist/dh2-engine.mjs (gitignored;
 * consumers vendor a copy — rogue-trader-2e: tools/vendor-engine.mjs).
 */
import { build } from 'esbuild';
import { writeFileSync, mkdirSync, readFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join, resolve } from 'path';
import { ruleSources, weaponsJson, RULE_FILES } from '../api/lib/rules/sources.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const buildDir = join(root, '.build');
const outFile = join(root, 'dist', 'dh2-engine.mjs');
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;

mkdirSync(buildDir, { recursive: true });

// 1. inline the data (no filesystem inside the host)
const browserSourcesPath = join(buildDir, 'sources.browser.mjs');
writeFileSync(browserSourcesPath, `// AUTO-GENERATED by scripts/build-engine-lib.mjs — do not edit.
export const RULE_FILES = ${JSON.stringify(RULE_FILES)};
export const ruleSources = ${JSON.stringify(ruleSources)};
export const weaponsJson = ${JSON.stringify(weaponsJson)};
`);

// 2. library entry: dispatch + the character-schema helpers hosts need locally
const entryPath = join(buildDir, 'engine-lib-entry.mjs');
writeFileSync(entryPath, `// AUTO-GENERATED by scripts/build-engine-lib.mjs — do not edit.
export { dispatch } from ${JSON.stringify(join(root, 'api', 'lib', 'api-router.mjs'))};
export {
    CHARACTER_SCHEMA_VERSION, CHARACTER_FIELDS, LEDGER_KINDS,
    migrateCharacter, validateCharacter, emptyCharacter,
    characterToCombatant, characteristicTotal, characteristicBonus, skillTarget,
} from ${JSON.stringify(join(root, 'api', 'lib', 'character-schema.mjs'))};
export const ENGINE_LIB_VERSION = ${JSON.stringify(version)};
`);

mkdirSync(dirname(outFile), { recursive: true });
await build({
    entryPoints: [entryPath],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: ['es2020'],
    outfile: outFile,
    legalComments: 'none',
    logLevel: 'warning',
    keepNames: true,
    plugins: [{
        name: 'browser-sources',
        setup(b) {
            b.onResolve({ filter: /[\\/]sources\.mjs$/ }, () => ({ path: browserSourcesPath }));
        },
    }],
});

console.log(`✓ Engine library built → dist/dh2-engine.mjs (v${version})`);
